"""Export the strategies as TradingView Pine Script v6.

TradingView cannot run this Python package, so the strategies are emitted as
native Pine strategies instead. They mirror the Python versions deliberately:

* the same stance rules and default parameters
* the same risk block: percentage stop, trailing stop, optional target
* the same execution timing, since Pine with ``process_orders_on_close=false``
  fills on the next bar's open, exactly as this engine does

They will not match the Python backtest to the cent. TradingView uses its own
data, its own dividend adjustment, and its own intrabar fill assumptions. Treat
a large divergence as a question worth asking, not as proof either side is
wrong.
"""

from __future__ import annotations

from typing import Dict

from .strategies import REGISTRY

INSTRUCTIONS = """
To use these on TradingView:

  1. Open a chart, then the Pine Editor tab at the bottom of the screen.
  2. Open a new blank strategy, select all of the placeholder code, delete it.
  3. Paste the contents of one .pine file.
  4. Click Save, give it a name, then Add to chart.
  5. The Strategy Tester tab at the bottom shows the backtest results.

Set the chart to Daily before judging any of these. They are daily bar
strategies, and running them on a 5 minute chart tests something else entirely.

A free TradingView account limits how much history the Strategy Tester covers,
so its numbers will differ from a long Python backtest for that reason alone.
"""

_HEADER = """//@version=6
// {title}
// Generated by tradingbot. Mirrors the Python strategy of the same name.
//
// Execution timing matches the Python engine: process_orders_on_close is false,
// so a signal computed on this bar's close is filled at the next bar's open.
strategy("{title}", overlay={overlay}, initial_capital=10000,
     default_qty_type=strategy.percent_of_equity, default_qty_value=20,
     commission_type=strategy.commission.percent, commission_value=0.0,
     slippage=1, process_orders_on_close=false, calc_on_every_tick=false,
     pyramiding=0)

// ---------------------------------------------------------------- direction
dirMode = input.string("long", "Direction", options=["long", "short", "both"],
     tooltip="Which sides this strategy may take. Shorting carries unlimited loss exposure.")
allowLong  = dirMode == "long"  or dirMode == "both"
allowShort = dirMode == "short" or dirMode == "both"
"""

_RISK_BLOCK = """
// -------------------------------------------------------------------- risk
grpRisk   = "Risk"
useStop   = input.bool(true,  "Stop loss",     group=grpRisk)
stopPct   = input.float(8.0,  "Stop loss %",   minval=0.1, maxval=90, step=0.5, group=grpRisk)
useTrail  = input.bool(false, "Trailing stop", group=grpRisk)
trailPct  = input.float(15.0, "Trailing %",    minval=0.1, maxval=90, step=0.5, group=grpRisk)
useTarget = input.bool(false, "Take profit",   group=grpRisk)
targetPct = input.float(20.0, "Take profit %", minval=0.1, step=0.5, group=grpRisk)

// --------------------------------------------------------------- execution
// stance: 1 wants long, -1 wants short, 0 wants flat, na means leave it alone.
// Everything below is top level rather than inside functions, because Pine
// places restrictions on strategy calls made from user defined functions.
posSign = math.sign(strategy.position_size)
target  = na(stance) ? posSign : stance
target := not allowLong  and target > 0 ? 0.0 : target
target := not allowShort and target < 0 ? 0.0 : target

if target > 0 and posSign <= 0
    strategy.entry("long", strategy.long)
else if target < 0 and posSign >= 0
    strategy.entry("short", strategy.short)
else if target == 0 and posSign != 0
    strategy.close_all(comment="signal neutral")

// Water marks for the trailing stop, tracked on closes exactly as the Python
// engine does. Computing the stop price explicitly avoids Pine's ambiguity
// over whether trail_offset is measured in ticks or in price.
var float hiWater = na
var float loWater = na
if strategy.position_size == 0
    hiWater := na
    loWater := na
else
    hiWater := na(hiWater) ? close : math.max(hiWater, close)
    loWater := na(loWater) ? close : math.min(loWater, close)

entryPx = strategy.position_avg_price

if strategy.position_size > 0
    float longStop = useStop ? entryPx * (1 - stopPct / 100) : na
    if useTrail and not na(hiWater)
        trailStop = hiWater * (1 - trailPct / 100)
        longStop := na(longStop) ? trailStop : math.max(longStop, trailStop)
    float longTarget = useTarget ? entryPx * (1 + targetPct / 100) : na
    strategy.exit("exit long", from_entry="long", stop=longStop, limit=longTarget)

if strategy.position_size < 0
    float shortStop = useStop ? entryPx * (1 + stopPct / 100) : na
    if useTrail and not na(loWater)
        trailStop = loWater * (1 + trailPct / 100)
        shortStop := na(shortStop) ? trailStop : math.min(shortStop, trailStop)
    float shortTarget = useTarget ? entryPx * (1 - targetPct / 100) : na
    strategy.exit("exit short", from_entry="short", stop=shortStop, limit=shortTarget)
"""


