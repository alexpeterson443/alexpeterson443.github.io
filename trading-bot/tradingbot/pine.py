def generate(name: str) -> str:
    """Return the Pine Script source for one registered strategy."""
    if name not in REGISTRY:
        raise ValueError(
            f"unknown strategy {name!r}; available: {', '.join(sorted(REGISTRY))}"
        )
    if name not in _BODIES:
        raise ValueError(f"no Pine Script template for {name!r}")
    spec = _BODIES[name]
    header = _HEADER.format(title=spec["title"], overlay=spec["overlay"])
    return header + spec["body"] + _RISK_BLOCK + _FOOTER


def generate_all() -> Dict[str, str]:
    return {name: generate(name) for name in sorted(_BODIES)}
